import { WEIGHT_BASIS_LABEL } from "@/lib/scoring";
import { getIdeaBundle, versionToFields } from "./ideas";

/** A copyable project brief. Personal-relevance details are included only when asked. */
export async function ideaBriefMarkdown(workspaceId: string, ideaId: string, opts: { includePersonal?: boolean } = {}) {
  const b = await getIdeaBundle(workspaceId, ideaId);
  if (!b) throw new Error("Idea not found");
  const f = versionToFields(b.current);
  const L: string[] = [`# ${f.name}`, "", `> ${f.summary}`, ""];
  if (b.hackathon) L.push(`**Hackathon:** ${b.hackathon.name}${b.hackathon.deadlineAt ? ` · deadline ${b.hackathon.deadlineAt.toISOString()}` : ""}`, "");
  L.push("## Problem", "", f.userProblem || "_Not stated_", "", "## Target user", "", f.targetAudience || "_Not stated_", "", "## How it works", "", f.workflow || "_Not stated_", "");
  L.push("## Features", "", ...(f.features.length ? f.features.map((x) => `- ${x}`) : ["- _None listed_"]), "");
  if (f.differentiators.length) L.push("## Claimed differentiators", "", ...f.differentiators.map((x) => `- ${x}`), "");
  if (f.sponsorUsage) L.push("## Sponsor technology", "", f.sponsorUsage, "");
  if (opts.includePersonal && b.idea.personalRelevance?.experiences) L.push("## Personal relevance (user-reported)", "", b.idea.personalRelevance.example || "Yes", "");
  if (b.latest) {
    L.push("## Assessment against the official rubric", "", `_${WEIGHT_BASIS_LABEL[b.latest.weightBasis]} · ${b.latest.method === "ai" ? "Verdict (AI)" : "rule-based"} · AI-assisted planning estimate, not an official score or a prediction._`, "");
    L.push("| Criterion | Weight | Rating |", "|---|---|---|", ...b.latest.criterionResults.map((r) => `| ${r.name} | ${r.weight ?? "—"} | ${r.rating}/5 |`), "", `**Weighted estimate:** ${b.latest.weightedTotal ?? "—"} / 100`, "");
  }
  const o = b.idea.originality;
  if (o) {
    L.push("## Originality research", "", `Research confidence: **${o.confidence.level}** — ${o.confidence.explanation}`, "");
    if (o.closest.length) L.push("Closest existing projects:", "", ...o.closest.map((c) => `- [${c.name}](${c.url}) — ${c.level} overlap. ${c.why}`), "");
    L.push("Limitations:", "", ...o.limitations.map((l) => `- ${l}`), "");
  }
  L.push("## Version history", "", ...b.versions.map((v) => `- v${v.version} (${v.createdAt.toISOString().slice(0, 10)}, ${v.changeSource}): ${v.changeNote ?? ""}`), "");
  L.push("---", "_Generated by RubricRoom. Sources and assessments are traceable in the workspace._");
  return L.join("\n");
}
